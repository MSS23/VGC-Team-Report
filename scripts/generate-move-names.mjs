import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const POKEAPI_COMMIT = "e21557dd4cd0fefe7cb1f946bf9080e38a2e3ba4";
const SOURCE_URL = `https://raw.githubusercontent.com/PokeAPI/pokeapi/${POKEAPI_COMMIT}/data/v2/csv/move_names.csv`;
const OUTPUT_URL = new URL("../src/lib/data/move-names.ts", import.meta.url);

// PokéAPI language IDs: Korean, French, Spanish, Italian, English,
// Japanese (kanji/kana), and Simplified Chinese.
const LANGUAGES = new Map([
  [3, "ko"],
  [5, "fr"],
  [7, "es"],
  [8, "it"],
  [9, "en"],
  [11, "ja"],
  [12, "zh"],
]);
const TARGET_LANGUAGES = ["fr", "it", "es", "ja", "ko", "zh"];

function parseCsvRow(row) {
  const fields = [];
  let value = "";
  let quoted = false;

  for (let index = 0; index < row.length; index += 1) {
    const character = row[index];
    if (character === '"') {
      if (quoted && row[index + 1] === '"') {
        value += '"';
        index += 1;
      } else {
        quoted = !quoted;
      }
    } else if (character === "," && !quoted) {
      fields.push(value);
      value = "";
    } else {
      value += character;
    }
  }

  fields.push(value);
  return fields;
}

const response = await fetch(SOURCE_URL);
if (!response.ok) {
  throw new Error(`Unable to download move names: ${response.status} ${response.statusText}`);
}

const csv = await response.text();
const movesById = new Map();

for (const row of csv.split(/\r?\n/).slice(1)) {
  if (!row) continue;
  const [moveIdText, languageIdText, name] = parseCsvRow(row);
  const language = LANGUAGES.get(Number(languageIdText));
  if (!language || !name) continue;

  const moveId = Number(moveIdText);
  const translations = movesById.get(moveId) ?? {};
  translations[language] = name;
  movesById.set(moveId, translations);
}

const entriesById = [...movesById.entries()]
  .filter(([, translations]) => translations.en)
  .sort(([left], [right]) => left - right);

// Some battle-only moves (notably generic Z-Moves) have separate physical and
// special IDs with the same display name. The app looks up by English name, so
// merge those records into one deterministic catalogue entry.
const entriesByEnglishName = new Map();
for (const [moveId, translations] of entriesById) {
  const existing = entriesByEnglishName.get(translations.en);
  if (existing) {
    Object.assign(existing.translations, translations);
  } else {
    entriesByEnglishName.set(translations.en, { moveId, translations });
  }
}
const entries = [...entriesByEnglishName.values()]
  .sort((left, right) => left.moveId - right.moveId)
  .map(({ moveId, translations }) => [moveId, translations]);

const output = [
  "// Generated by scripts/generate-move-names.mjs. Do not edit by hand.",
  `// Source: ${SOURCE_URL}`,
  "// English is the canonical source key; presentation languages are values.",
  'export type MoveTranslationLanguage = "fr" | "it" | "es" | "ja" | "ko" | "zh";',
  "",
  "export const MOVE_NAMES: Record<string, Partial<Record<MoveTranslationLanguage, string>>> = {",
];

for (const [, translations] of entries) {
  const values = TARGET_LANGUAGES
    .filter((language) => translations[language])
    .map((language) => `${language}: ${JSON.stringify(translations[language])}`)
    .join(", ");
  output.push(`  ${JSON.stringify(translations.en)}: { ${values} },`);
}

output.push("};", "");
await writeFile(fileURLToPath(OUTPUT_URL), output.join("\n"), "utf8");

const coverage = Object.fromEntries(
  TARGET_LANGUAGES.map((language) => [
    language,
    entries.filter(([, translations]) => translations[language]).length,
  ]),
);

console.log(`Generated ${entries.length} English move names in ${fileURLToPath(OUTPUT_URL)}`);
console.log("Translation coverage:", coverage);
